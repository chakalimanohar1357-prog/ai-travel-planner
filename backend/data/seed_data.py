def jitter(coord, spread=0.03):
    """
    Returns the coordinate shifted by a small random amount, so that a
    destination's hotels/restaurants/attractions don't all sit on the exact
    same map pin. Falls back to the original value if coord is None.
    """
    if coord is None:
        return coord
    return coord + random.uniform(-spread, spread)


